def load_rmbench_dataset(dataset_name: str, split: str, max_examples: int | None) -> list[dict]:
    dataset = load_dataset(dataset_name, split=split)
    if max_examples is not None:
        dataset = dataset.select(range(min(max_examples, len(dataset))))

    records: list[dict] = []
    for idx, row in enumerate(dataset):
        prompt_id = str(row.get("id", idx))
        prompt = row.get("prompt", "")
        chosen = row.get("chosen") or []
        rejected = row.get("rejected") or []
        domain = row.get("domain", "unknown") or "unknown"

        records.append(
            {
                "id": prompt_id,
                "prompt": prompt,
                "chosen": list(chosen),
                "rejected": list(rejected),
                "domain": domain,
            }
        )
    return records


def _normalize_domain(domain: str) -> str:
    if not domain:
        return "unknown"
    lowered = domain.lower()
    for canonical in DOMAIN_ORDER:
        if lowered.startswith(canonical):
            return canonical
    if lowered.startswith("safety"):
        return "safety"
    return lowered


def _safe_mean(values: Iterable[float]) -> float:
    valid = [value for value in values if value is not None and not math.isnan(value)]
    return float(sum(valid) / len(valid)) if valid else math.nan


def _build_metric_entry(acc_matrix: np.ndarray) -> dict[str, Any]:
    difficulties = _compute_difficulty(acc_matrix)
    score = _safe_mean(difficulties[level] for level in DIFFICULTY_LEVELS)
    return {
        "matrix": acc_matrix.tolist(),
        "easy": difficulties["easy"],
        "normal": difficulties["normal"],
        "hard": difficulties["hard"],
        "score": score,
    }


def resolve_dataset_split(dataset_name: str, requested_split: str | None) -> str:
    """Return the split to use for a dataset, honoring overrides when provided."""

    if requested_split:
        return requested_split

    return "train"


def prepare_model_paths(
    args: argparse.Namespace,
    output_dir: Path,
) -> tuple[Path | str, Path | str | None, Path | None]:
    checkpoint_dir: Path | None = None
    actor_export: Path | str | None = args.actor_hf_path
    critic_export: Path | str | None = args.critic_hf_path
    critic_ckpt: Path | str | None = args.critic_hf_path

    if args.checkpoint_root is not None:
        checkpoint_root = args.checkpoint_root.resolve()
        if args.checkpoint_step:
            step_dir = args.checkpoint_step
            if not step_dir.startswith("global_step_"):
                step_dir = f"global_step_{step_dir}"
            checkpoint_dir = checkpoint_root / step_dir
            if not checkpoint_dir.exists():
                raise FileNotFoundError(f"Specified checkpoint step not found: {checkpoint_dir}")
        else:
            checkpoint_dir = find_latest_checkpoint(checkpoint_root)

        actor_ckpt = checkpoint_dir / "actor"
        critic_ckpt = checkpoint_dir / "critic"

        export_root = output_dir / "hf_exports" / checkpoint_dir.name
        actor_export = export_root / "actor"
        critic_export = export_root / "critic"

        if not (args.reuse_export and (Path(actor_export) / "config.json").exists()):
            ensure_hf_export(actor_ckpt, Path(actor_export))
        if not args.skip_critic and critic_export is not None:
            if not (args.reuse_export and (Path(critic_export) / "config.json").exists()):
                ensure_hf_export(critic_ckpt, Path(critic_export))

    if actor_export is None:
        raise ValueError("Either --checkpoint-root or --actor-hf-path must be provided.")

    return actor_export, critic_export, checkpoint_dir


def _build_pair_samples(records: list[dict]) -> tuple[list[PairSample], dict[str, dict]]:
    pair_samples: list[PairSample] = []
    metadata: dict[str, dict] = {}

    for record in records:
        prompt_id = record["id"]
        prompt_text = record["prompt"]
        raw_domain = record["domain"] or "unknown"
        domain = _normalize_domain(raw_domain)
        chosen_list = record["chosen"]
        rejected_list = record["rejected"]

        for i, chosen in enumerate(chosen_list):
            for j, rejected in enumerate(rejected_list):
                base_id = f"{prompt_id}-c{i}-r{j}"
                metadata[base_id] = {
                    "sample_id": prompt_id,
                    "domain": domain,
                    "raw_domain": raw_domain,
                    "i": i,
                    "j": j,
                }

                forward_messages = build_prompt_messages(prompt_text, chosen, rejected)
                pair_samples.append(
                    PairSample(
                        prompt_id=prompt_id,
                        subset=domain,
                        pair_index=len(pair_samples),
                        messages=forward_messages,
                        response_1=chosen,
                        response_2=rejected,
                        ground_truth="response_1",
                        prompt_text=prompt_text,
                        base_pair_id=base_id,
                        orientation="forward",
                        original_chosen=chosen,
                        original_rejected=rejected,
                    )
                )

                backward_messages = build_prompt_messages(prompt_text, rejected, chosen)
                pair_samples.append(
                    PairSample(
                        prompt_id=prompt_id,
                        subset=domain,
                        pair_index=len(pair_samples),
                        messages=backward_messages,
                        response_1=rejected,
                        response_2=chosen,
                        ground_truth="response_2",
                        prompt_text=prompt_text,
                        base_pair_id=base_id,
                        orientation="backward",
                        original_chosen=chosen,
                        original_rejected=rejected,
                    )
                )

    return pair_samples, metadata


def _aggregate_sample_records(
    aggregated_samples: Iterable[PairSample],
    metadata: dict[str, dict],
) -> dict[str, dict]:
    records: dict[str, dict] = {}
    for sample in aggregated_samples:
        base_id = sample.base_pair_id
        if base_id not in metadata:
            continue
        meta = metadata[base_id]
        sample_id = meta["sample_id"]
        domain = meta["domain"]
        i = meta["i"]
        j = meta["j"]

        record = records.setdefault(
            sample_id,
            {
                "domain": domain,
                "actor_matrix_strict": np.zeros((3, 3), dtype=float),
                "actor_matrix_loose": np.zeros((3, 3), dtype=float),
                "critic_matrix_strict": np.zeros((3, 3), dtype=float),
                "critic_matrix_loose": np.zeros((3, 3), dtype=float),
            },
        )

        actor_score = float(estimate_actor_probability(sample))
        critic_score = sample.corrected_score if sample.corrected_score is not None else actor_score
        critic_score = float(np.clip(critic_score, 0.0, 1.0))

        record["actor_matrix_strict"][i, j] = 1.0 if actor_score > 0.5 else 0.0
        record["actor_matrix_loose"][i, j] = actor_score
        record["critic_matrix_strict"][i, j] = 1.0 if critic_score > 0.5 else 0.0
        record["critic_matrix_loose"][i, j] = critic_score

    return records


def _compute_difficulty(acc_matrix: np.ndarray) -> dict[str, float]:
    n = acc_matrix.shape[0]
    upper_right_count = n * (n - 1) / 2
    lower_left_count = upper_right_count

    hard = (
        float(np.triu(acc_matrix, k=1).sum()) / upper_right_count if upper_right_count > 0 else math.nan
    )
    normal = float(np.diag(acc_matrix).mean()) if n > 0 else math.nan
    easy = (
        float(np.tril(acc_matrix, k=-1).sum()) / lower_left_count if lower_left_count > 0 else math.nan
    )
    return {"hard": hard, "normal": normal, "easy": easy}


def compute_rmbench_metrics(sample_records: dict[str, dict]) -> dict:
    if not sample_records:
        return {
            "overall": {},
            "domains": {},
            "difficulty": {},
            "num_samples": 0,
        }

    overall_sums = {
        mode: {variant: np.zeros((3, 3), dtype=float) for variant in SCORE_VARIANTS}
        for mode in AGG_MODES
    }
    domain_sums: dict[str, dict[str, dict[str, np.ndarray]]] = defaultdict(
        lambda: {
            mode: {variant: np.zeros((3, 3), dtype=float) for variant in SCORE_VARIANTS}
            for mode in AGG_MODES
        }
    )
    domain_counts: dict[str, int] = defaultdict(int)

    for record in sample_records.values():
        domain = record["domain"]
        for mode in AGG_MODES:
            for variant in SCORE_VARIANTS:
                key = f"{mode}_matrix_{variant}"
                matrix = record[key]
                overall_sums[mode][variant] += matrix
                domain_sums[domain][mode][variant] += matrix
        domain_counts[domain] += 1

    num_samples = len(sample_records)
    domain_metrics: dict[str, dict[str, Any]] = {}
    for domain, sums in domain_sums.items():
        count = domain_counts[domain]
        entry: dict[str, Any] = {"count": count}
        for mode in AGG_MODES:
            entry[mode] = {}
            for variant in SCORE_VARIANTS:
                acc_matrix = sums[mode][variant] / count
                entry[mode][variant] = _build_metric_entry(acc_matrix)
        domain_metrics[domain] = entry

    overall_metrics: dict[str, dict[str, Any]] = {mode: {} for mode in AGG_MODES}
    difficulty_summary: dict[str, dict[str, Any]] = {mode: {} for mode in AGG_MODES}

    for mode in AGG_MODES:
        for variant in SCORE_VARIANTS:
            overall_matrix = overall_sums[mode][variant] / num_samples
            prompt_weighted = _build_metric_entry(overall_matrix)

            domain_scores: dict[str, float] = {}
            for domain in DOMAIN_ORDER:
                if domain in domain_metrics:
                    domain_scores[domain] = domain_metrics[domain][mode][variant]["score"]
                else:
                    domain_scores[domain] = math.nan

            overall_score = _safe_mean(domain_scores.values())
            difficulty_scores = {
                level: _safe_mean(
                    domain_metrics[domain][mode][variant][level]
                    for domain in DOMAIN_ORDER
                    if domain in domain_metrics
                )
                for level in DIFFICULTY_LEVELS
            }
            difficulty_scores_with_total = dict(difficulty_scores)
            difficulty_scores_with_total["score"] = overall_score

            overall_metrics[mode][variant] = {
                "score": overall_score,
                "domain_scores": domain_scores,
                "difficulty_scores": difficulty_scores_with_total,
                "prompt_weighted": prompt_weighted,
            }
            difficulty_summary[mode][variant] = difficulty_scores_with_total

    return {
        "overall": overall_metrics,
        "domains": domain_metrics,
        "difficulty": difficulty_summary,
        "num_samples": num_samples,
    }


def main() -> None:
    args = parse_args()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    actor_export, critic_export, checkpoint_dir = prepare_model_paths(args, output_dir)

    split = resolve_dataset_split(args.dataset, args.split)
    if args.split is None and split:
        print(f"[info] No split specified for {args.dataset}; defaulting to '{split}'.", file=sys.stderr)

    records = load_rmbench_dataset(args.dataset, split, args.max_examples)
    if not records:
        raise RuntimeError("No RM-Bench samples were constructed.")

    pair_samples, pair_metadata = _build_pair_samples(records)

    num_gpus = torch.cuda.device_count()
    dtype = torch.bfloat16 if num_gpus > 0 else torch.float32
    device = torch.device("cuda" if num_gpus > 0 else "cpu")

    actor_tokenizer_source = args.actor_hf_tokenizer or actor_export
    actor_tokenizer = AutoTokenizer.from_pretrained(actor_tokenizer_source, trust_remote_code=True)
    actor_tokenizer.padding_side = "left"

    actor_backend = args.actor_backend.lower()
    actor_model_ref = actor_export
    critic_outputs_logits = args.critic_loss_type == "mle"

    if actor_backend == "server":
        server_proc: subprocess.Popen | None = None
        try:
            server_proc = start_vllm_server(Path(actor_model_ref), args.server_port, args.actor_data_parallel_size)
            wait_for_server_ready(args.server_port, args.server_startup_timeout)
            run_actor_generation_vllm_server(
                actor_tokenizer,
                pair_samples,
                str(actor_model_ref),
                args.server_port,
                args.max_new_tokens,
                args.actor_request_concurrency,
                args.actor_request_timeout,
            )
        finally:
            shutdown_process(server_proc, args.server_shutdown_timeout)
    elif actor_backend == "vllm":
        if num_gpus == 0:
            raise RuntimeError("vLLM backend requires CUDA but no GPU was detected.")
        try:
            from vllm import LLM, SamplingParams
        except ImportError as exc:  # pragma: no cover
            raise RuntimeError("vLLM is not installed; re-run with --actor-backend hf or install vllm.") from exc

        dtype_str = "bfloat16" if dtype == torch.bfloat16 else "float32"
        actor_llm = LLM(
            model=str(actor_model_ref),
            tokenizer=str(actor_model_ref),
            trust_remote_code=True,
            dtype=dtype_str,
            tensor_parallel_size=args.tensor_parallel_size,
            gpu_memory_utilization=args.gpu_memory_utilization,
        )
        sampling_params = SamplingParams(
            max_tokens=args.max_new_tokens,
            temperature=0.0,
            logprobs=1,
        )
        run_actor_generation_vllm_local(actor_llm, sampling_params, actor_tokenizer, pair_samples, args.actor_batch_size)
    else:
        actor_model = AutoModelForCausalLM.from_pretrained(
            actor_model_ref,
            torch_dtype=dtype,
            trust_remote_code=True,
        ).to(device)
        run_actor_generation_hf(actor_model, actor_tokenizer, pair_samples, args.max_new_tokens, args.actor_batch_size)

    run_critic = not args.skip_critic and critic_export is not None
    critic_workers: int = 0
    if run_critic:
        critic_workers = args.critic_num_workers or 0
        if num_gpus == 0:
            critic_workers = 1
        else:
            critic_workers = critic_workers or num_gpus
            critic_workers = max(1, min(critic_workers, num_gpus))

        critic_model_ref = critic_export
        if checkpoint_dir is None and not Path(str(critic_model_ref)).exists():
            raise ValueError("--critic-hf-path must point to a local directory when using baseline evaluation.")

        if critic_workers > 1:
            run_critic_scoring_multiproc(
                pair_samples,
                Path(critic_model_ref),
                Path(critic_export) if isinstance(critic_export, (str, Path)) else None,
                critic_outputs_logits,
                dtype,
                args.critic_batch_size,
                critic_workers,
            )
        else:
            critic_model, critic_tokenizer = load_token_classifier(
                Path(critic_model_ref),
                dtype,
                Path(critic_export) if isinstance(critic_export, (str, Path)) else None,
            )
            critic_model.to(device)
            run_critic_scoring_single(
                critic_model,
                critic_tokenizer,
                pair_samples,
                args.critic_batch_size,
                critic_outputs_logits,
            )

    apply_correction(pair_samples, args.threshold)
    raw_samples = list(pair_samples)
    aggregated_samples = aggregate_pair_orientations(pair_samples)

    sample_records = _aggregate_sample_records(aggregated_samples, pair_metadata)
    metrics_summary = compute_rmbench_metrics(sample_records)

    actor_prediction_distribution = compute_prediction_distribution(aggregated_samples, "predicted_label")
    critic_prediction_distribution = compute_prediction_distribution(aggregated_samples, "corrected_label")

    run_name = derive_run_name(actor_model_ref, checkpoint_dir)
    artifact_paths = resolve_output_artifacts(output_dir, args.results_file, run_name)

    generations_path = artifact_paths["generations"]
    save_request_generations(raw_samples, generations_path)

    pair_results = build_pair_level_results(raw_samples)
    pair_results_path = artifact_paths["pairs"]
    save_pair_level_results(pair_results, pair_results_path)
    pair_status_summary = summarize_pair_statuses(pair_results)

    metrics_config = {
        "checkpoint_dir": str(checkpoint_dir) if checkpoint_dir is not None else None,
        "threshold": args.threshold,
        "dataset": args.dataset,
        "split": split,
        "max_examples": args.max_examples,
        "actor_batch_size": args.actor_batch_size,
        "critic_batch_size": args.critic_batch_size,
        "max_new_tokens": args.max_new_tokens,
        "actor_backend": actor_backend,
        "critic_num_workers": critic_workers,
        "actor_model_ref": str(actor_model_ref),
        "skip_critic": args.skip_critic,
        "critic_model_ref": str(critic_export) if critic_export is not None else None,
        "critic_loss_type": args.critic_loss_type,
        "run_name": run_name,
    }

    metrics_config.update(
        {
            "generation_path": str(generations_path),
            "pair_results_path": str(pair_results_path),
        }
    )

    if actor_backend == "vllm":
        metrics_config.update(
            {
                "tensor_parallel_size": args.tensor_parallel_size,
                "gpu_memory_utilization": args.gpu_memory_utilization,
            }
        )
    elif actor_backend == "server":
        metrics_config.update(
            {
                "actor_data_parallel_size": args.actor_data_parallel_size,
                "actor_request_concurrency": args.actor_request_concurrency,
                "actor_request_timeout": args.actor_request_timeout,
                "server_port": args.server_port,
            }
        )

    total_pairs = len(aggregated_samples)

    metrics = {
        "summary": metrics_summary,
        "prediction_distribution": {
            "actor": actor_prediction_distribution,
            "critic": critic_prediction_distribution,
        },
        "pair_status_summary": pair_status_summary,
        "total_pairs": total_pairs,
        "config": metrics_config,
    }

    if args.wandb_project:
        os.environ["WANDB_PROJECT"] = args.wandb_project
    if args.wandb_group:
        os.environ["WANDB_GROUP"] = args.wandb_group
    if args.wandb_run_name:
        os.environ["WANDB_RUN_NAME"] = args.wandb_run_name
    if args.wandb_mode:
        os.environ["WANDB_MODE"] = args.wandb_mode

    wandb_project = os.getenv("WANDB_PROJECT")
    wandb_group = os.getenv("WANDB_GROUP")
    wandb_run_name = os.getenv("WANDB_RUN_NAME")
    wandb_mode_env = os.getenv("WANDB_MODE", "online").lower()

    metrics_config.update(
        {
            "wandb_project": wandb_project,
            "wandb_group": wandb_group,
            "wandb_run_name": wandb_run_name,
            "wandb_mode": wandb_mode_env,
        }
    )

    output_path = artifact_paths["metrics"]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w") as fout:
        json.dump(metrics, fout, indent=2)

    if wandb and wandb_mode_env not in {"disabled", "off", "offline"}:
        try:
            run = wandb.init(
                project=wandb_project or "verl_think_rm",
                group=wandb_group,
                job_type="rmbench_eval",
                name=wandb_run_name,
                config=metrics["config"],
            )

            def _maybe_add(target: dict[str, float], key: str, value: Any) -> None:
                if value is None:
                    return
                if isinstance(value, float) and math.isnan(value):
                    return
                target[key] = value

            overall = metrics_summary.get("overall", {})
            pair_summary = metrics.get("pair_status_summary", {})

            actor_pair_status = pair_summary.get("actor", {})
            critic_pair_status = pair_summary.get("critic", {})

            core_payload: dict[str, float] = {}
            for mode in AGG_MODES:
                mode_overall = overall.get(mode, {})
                for variant in SCORE_VARIANTS:
                    variant_stats = mode_overall.get(variant, {})
                    prefix = f"rmbench-core/{mode}/{variant}"
                    _maybe_add(core_payload, f"{prefix}/overall", variant_stats.get("score"))

                    difficulty_scores = variant_stats.get("difficulty_scores") or {}
                    for level in DIFFICULTY_LEVELS:
                        _maybe_add(core_payload, f"{prefix}/difficulty/{level}", difficulty_scores.get(level))

                    domain_scores = variant_stats.get("domain_scores") or {}
                    for domain in DOMAIN_ORDER:
                        _maybe_add(core_payload, f"{prefix}/domain/{domain}", domain_scores.get(domain))

            _maybe_add(core_payload, "rmbench-core/actor/pair_consistency_rate", actor_pair_status.get("consistency_rate"))
            _maybe_add(core_payload, "rmbench-core/critic/pair_consistency_rate", critic_pair_status.get("consistency_rate"))
            _maybe_add(core_payload, "rmbench-core/num_samples", metrics_summary.get("num_samples"))
            _maybe_add(core_payload, "rmbench-core/total_pairs", metrics.get("total_pairs"))

            aux_payload: dict[str, float] = {}
            for domain, stats in metrics_summary.get("domains", {}).items():
                prefix = f"rmbench-aux/domains/{domain}"
                _maybe_add(aux_payload, f"{prefix}/count", stats.get("count"))
                for mode in AGG_MODES:
                    mode_stats = stats.get(mode, {})
                    for variant in SCORE_VARIANTS:
                        variant_stats = mode_stats.get(variant, {})
                        variant_prefix = f"{prefix}/{mode}/{variant}"
                        _maybe_add(aux_payload, f"{variant_prefix}/score", variant_stats.get("score"))
                        for level in DIFFICULTY_LEVELS:
                            _maybe_add(aux_payload, f"{variant_prefix}/{level}", variant_stats.get(level))

            for mode in AGG_MODES:
                mode_overall = overall.get(mode, {})
                for variant in SCORE_VARIANTS:
                    prompt_weighted = mode_overall.get(variant, {}).get("prompt_weighted", {})
                    prefix = f"rmbench-aux/overall_prompt_weighted/{mode}/{variant}"
                    for level in (*DIFFICULTY_LEVELS, "score"):
                        _maybe_add(aux_payload, f"{prefix}/{level}", prompt_weighted.get(level))

            for mode, stats in (("actor", actor_pair_status), ("critic", critic_pair_status)):
                rates = stats.get("rates", {}) if isinstance(stats, dict) else {}
                prefix = f"rmbench-aux/pair_status/{mode}"
                _maybe_add(aux_payload, f"{prefix}/clear_right_rate", rates.get("clear_right"))
                _maybe_add(aux_payload, f"{prefix}/clear_wrong_rate", rates.get("clear_wrong"))
                _maybe_add(aux_payload, f"{prefix}/unclear_rate", rates.get("unclear"))
                _maybe_add(aux_payload, f"{prefix}/total_pairs", stats.get("total"))

            run.log(core_payload)
            if aux_payload:
                run.log(aux_payload)
        except Exception as exc:  # pragma: no cover
            print(f"[WARN] WandB logging failed: {exc}")


if __name__ == "__main__":
    main()
